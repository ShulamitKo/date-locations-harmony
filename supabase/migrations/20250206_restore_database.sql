-- ============================================

-- טריגר לעדכון updated_at בטבלת reports
drop trigger if exists update_reports_updated_at on public.reports;
create trigger update_reports_updated_at
  before update on public.reports
  for each row
  execute function public.update_updated_at_column();

-- טריגר לניקוי אוטומטי של rate_limits
drop trigger if exists auto_cleanup_rate_limits on public.rate_limits;
create trigger auto_cleanup_rate_limits
  after insert or update on public.rate_limits
  for each statement
  execute function public.trigger_cleanup_expired_rate_limits();

-- טריגר לעדכון דירוג ממוצע אחרי הוספת/עדכון ביקורת
drop trigger if exists update_spot_rating_trigger on public.reviews;
create trigger update_spot_rating_trigger
  after insert or update or delete on public.reviews
  for each row
  execute function public.update_spot_rating();

